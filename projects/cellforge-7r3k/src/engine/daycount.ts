// Day-count conventions and coupon-date scheduling — the calendar arithmetic that
// every fixed-income security function is built on. Pure and React-free: everything
// takes and returns Excel **serials** (integer day numbers, the same epoch the rest
// of the app uses via `dates.ts`) and plain numbers.
//
// The five day-count *bases* are Excel's:
//
//   0  US (NASD) 30/360   — 30-day months, 360-day year, with the US end-of-month
//                           and 31st→30th/roll-forward quirks.
//   1  actual/actual      — real day counts; the year length follows the calendar
//                           (365 or 366), the convention behind `YEARFRAC` basis 1.
//   2  actual/360         — real days over a 360-day year (money-market).
//   3  actual/365         — real days over a 365-day year.
//   4  European 30/360    — 30-day months, but the 31st→30th rule applies to *both*
//                           endpoints unconditionally and there is no Feb exception.
//
// The coupon helpers (`couponPCD`/`couponNCD`/`couponNum` and the three day counts)
// reproduce Excel's COUP* family: coupon dates are generated by stepping the
// **maturity** date backward by whole `12/frequency`-month intervals, preserving an
// end-of-month maturity (so a bond maturing on the 30th of a 31-day-less month still
// lands on month-end). These drive PRICE / YIELD / DURATION / ACCRINT.

import { serialToDate, dateToSerial } from './dates'

export type Basis = 0 | 1 | 2 | 3 | 4

export function isLeapYear(year: number): boolean {
  return (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0
}

/** Days in `month` (1-based) of `year`. */
export function daysInMonth(year: number, month: number): number {
  return new Date(Date.UTC(year, month, 0)).getUTCDate()
}

function isLastOfMonth(year: number, month: number, day: number): boolean {
  return day === daysInMonth(year, month)
}

// ---------------------------------------------------------------------------
// 30/360 day counts
// ---------------------------------------------------------------------------

/**
 * The 30/360 signed day count between two serials. `european` selects the 30E/360
 * rule (both 31sts clamp to 30, no February handling); otherwise the US (NASD) rule
 * is used: a 31st start clamps to 30, a last-day-of-February start clamps to 30 (and
 * pulls a last-day-of-February end to 30 with it), and a 31st end clamps to 30 only
 * when the (already-adjusted) start sits on the 30th — the classic NASD quirk.
 */
export function days360(startSerial: number, endSerial: number, european: boolean): number {
  const s = serialToDate(startSerial)
  const e = serialToDate(endSerial)
  let d1 = s.day
  let d2 = e.day
  const m1 = s.month
  const m2 = e.month
  const y1 = s.year
  const y2 = e.year

  if (european) {
    if (d1 === 31) d1 = 30
    if (d2 === 31) d2 = 30
  } else {
    // US / NASD method.
    const startIsEomFeb = m1 === 2 && isLastOfMonth(y1, m1, s.day)
    const endIsEomFeb = m2 === 2 && isLastOfMonth(y2, m2, e.day)
    if (startIsEomFeb && endIsEomFeb) d2 = 30
    if (startIsEomFeb) d1 = 30
    if (d1 === 31) d1 = 30
    if (d2 === 31 && d1 === 30) d2 = 30
  }
  return (y2 - y1) * 360 + (m2 - m1) * 30 + (d2 - d1)
}

/** Excel `DAYS360(start, end, [method])` — `method` TRUE picks the European rule. */
export function days360Excel(startSerial: number, endSerial: number, european: boolean): number {
  return days360(startSerial, endSerial, european)
}

// ---------------------------------------------------------------------------
// actual/actual year fraction (YEARFRAC basis 1)
// ---------------------------------------------------------------------------

/** Does a Feb-29 fall in the closed interval [a, b] (a ≤ b)? */
function containsLeapDay(a: number, b: number): boolean {
  const da = serialToDate(a)
  const db = serialToDate(b)
  for (let y = da.year; y <= db.year; y++) {
    if (isLeapYear(y)) {
      const feb29 = dateToSerial(y, 2, 29)
      if (feb29 >= a && feb29 <= b) return true
    }
  }
  return false
}

/**
 * Excel's actual/actual year fraction. For periods spanning at most one year the
 * denominator is 366 when the interval touches a leap day (else 365); for longer
 * spans it is the *average* calendar-year length over the years touched — matching
 * the algorithm Excel/Sheets and the OpenOffice analysis add-in use for basis 1.
 */
function yearFracActAct(startSerial: number, endSerial: number): number {
  if (startSerial === endSerial) return 0
  const a = Math.min(startSerial, endSerial)
  const b = Math.max(startSerial, endSerial)
  const da = serialToDate(a)
  const db = serialToDate(b)
  const sign = endSerial >= startSerial ? 1 : -1

  const withinOneYear =
    da.year === db.year ||
    (da.year + 1 === db.year && (da.month > db.month || (da.month === db.month && da.day >= db.day)))

  if (withinOneYear) {
    let denom = 365
    if (da.year === db.year) {
      if (isLeapYear(da.year)) denom = 366
    } else if (containsLeapDay(a, b)) {
      denom = 366
    }
    return (sign * (b - a)) / denom
  }

  const years = db.year - da.year + 1
  const totalDays = dateToSerial(db.year + 1, 1, 1) - dateToSerial(da.year, 1, 1)
  const avg = totalDays / years
  return (sign * (b - a)) / avg
}

/**
 * `YEARFRAC(start, end, basis)` — the fraction of a year between two serials under a
 * given day-count basis. Symmetric in its arguments' order (Excel returns a positive
 * fraction regardless), except actual/actual carries the sign of the interval.
 */
export function yearFrac(startSerial: number, endSerial: number, basis: Basis): number | null {
  if (!Number.isFinite(startSerial) || !Number.isFinite(endSerial)) return null
  const a = Math.round(startSerial)
  const b = Math.round(endSerial)
  switch (basis) {
    case 0:
      return days360(a, b, false) / 360
    case 4:
      return days360(a, b, true) / 360
    case 1:
      return yearFracActAct(a, b)
    case 2:
      return (b - a) / 360
    case 3:
      return (b - a) / 365
    default:
      return null
  }
}

// ---------------------------------------------------------------------------
// Coupon-date scheduling (Excel COUP* family)
// ---------------------------------------------------------------------------

/**
 * Step a coupon anchor date `months` whole months (`months` may be negative).
 * When the anchor is the last day of its month the result is snapped to the last
 * day of the target month (end-of-month coupon convention); otherwise the anchor's
 * day-of-month is kept, clamped to the target month's length.
 */
function shiftCouponMonths(anchorSerial: number, months: number): number {
  const d = serialToDate(anchorSerial)
  const eom = isLastOfMonth(d.year, d.month, d.day)
  const idx = d.month - 1 + months
  const year = d.year + Math.floor(idx / 12)
  const month = ((idx % 12) + 12) % 12 + 1
  const last = daysInMonth(year, month)
  const day = eom ? last : Math.min(d.day, last)
  return dateToSerial(year, month, day)
}

const monthsPerCoupon = (frequency: number): number => Math.round(12 / frequency)

/**
 * The previous coupon date on or before `settlement` (Excel `COUPPCD`). Coupons are
 * generated from `maturity` backward; we walk back until we cross settlement.
 */
export function couponPCD(settlement: number, maturity: number, frequency: number): number {
  const step = monthsPerCoupon(frequency)
  let date = maturity
  // Walk back in whole coupon periods until we are at or before settlement.
  let guard = 0
  while (date > settlement && guard < 100000) {
    date = shiftCouponMonths(date, -step)
    guard++
  }
  return date
}

/** The next coupon date strictly after `settlement` (Excel `COUPNCD`). */
export function couponNCD(settlement: number, maturity: number, frequency: number): number {
  const pcd = couponPCD(settlement, maturity, frequency)
  return shiftCouponMonths(pcd, monthsPerCoupon(frequency))
}

/** Number of coupons payable between settlement (exclusive) and maturity (Excel `COUPNUM`). */
export function couponNum(settlement: number, maturity: number, frequency: number): number {
  const step = monthsPerCoupon(frequency)
  let date = maturity
  let n = 0
  let guard = 0
  while (date > settlement && guard < 100000) {
    date = shiftCouponMonths(date, -step)
    n++
    guard++
  }
  return n
}

/** Days from the previous coupon to settlement (Excel `COUPDAYBS`). */
export function coupDaysBS(settlement: number, maturity: number, frequency: number, basis: Basis): number {
  const pcd = couponPCD(settlement, maturity, frequency)
  return diffDays(pcd, settlement, basis)
}

/** Length of the coupon period containing settlement (Excel `COUPDAYS`). */
export function coupDays(settlement: number, maturity: number, frequency: number, basis: Basis): number {
  if (basis === 1) {
    const pcd = couponPCD(settlement, maturity, frequency)
    const ncd = shiftCouponMonths(pcd, monthsPerCoupon(frequency))
    return ncd - pcd
  }
  if (basis === 3) return 365 / frequency
  return 360 / frequency // bases 0, 2, 4
}

/** Days from settlement to the next coupon (Excel `COUPDAYSNC`). */
export function coupDaysNC(settlement: number, maturity: number, frequency: number, basis: Basis): number {
  if (basis === 0 || basis === 4) {
    // 30/360 bases: keep the identity COUPDAYS = COUPDAYBS + COUPDAYSNC exactly.
    return coupDays(settlement, maturity, frequency, basis) - coupDaysBS(settlement, maturity, frequency, basis)
  }
  const ncd = couponNCD(settlement, maturity, frequency)
  return diffDays(settlement, ncd, basis)
}

/** The day-count numerator between two serials under a basis (used by the COUP* helpers). */
export function diffDays(startSerial: number, endSerial: number, basis: Basis): number {
  if (basis === 0) return days360(startSerial, endSerial, false)
  if (basis === 4) return days360(startSerial, endSerial, true)
  return endSerial - startSerial // actual, for bases 1, 2, 3
}
