// Keccak-f[1600] and the SHA-3 family (FIPS 202), from scratch.
//
// The whole post-quantum shelf so far — Lamport, WOTS⁺, XMSS, SPHINCS⁺ — is
// *hash-based*. The other, larger branch of the NIST post-quantum standards is
// *lattice-based*, and every one of those (ML-KEM / FIPS 203, ML-DSA / FIPS 204)
// is built on SHA-3, not SHA-2. So before Curvefield can host a module-lattice
// KEM it needs the Keccak sponge: SHA3-256 (H), SHA3-512 (G), and the two
// extendable-output functions SHAKE128 (the XOF that expands a seed into a
// public matrix) and SHAKE256 (the PRF and the implicit-rejection KDF J).
//
// JavaScript has no 64-bit integer ALU, so — exactly as sha512.ts does for
// SHA-2 — the 25 lanes of the Keccak state are held as BigInt masked to 64 bits.
// Clear and obviously correct, which is what a lab wants; the sponge is driven
// through a byte view of the state so absorb/squeeze are plain XORs. Validated
// in the self-test against the FIPS 202 known-answer digests.

// JavaScript's bitwise operators are 32-bit, so each 64-bit Keccak lane is held
// as two 32-bit words — low at slot 2·i, high at 2·i+1 — in a Uint32Array of 50.
// This split-word form (the classic fast Keccak layout) keeps the permutation in
// integer registers instead of BigInt, which matters because ML-KEM leans on the
// sponge hard: expanding the public matrix and the noise alone is dozens of
// SHAKE squeezes per key, and the accumulated self-test drives 10,000 of them.

// Iota round constants (24 rounds), pre-split into high / low 32-bit halves.
const RC_HI = new Uint32Array([
  0x00000000, 0x00000000, 0x80000000, 0x80000000, 0x00000000, 0x00000000, 0x80000000, 0x80000000,
  0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x00000000, 0x80000000, 0x80000000, 0x80000000,
  0x80000000, 0x80000000, 0x00000000, 0x80000000, 0x80000000, 0x80000000, 0x00000000, 0x80000000,
])
const RC_LO = new Uint32Array([
  0x00000001, 0x00008082, 0x0000808a, 0x80008000, 0x0000808b, 0x80000001, 0x80008081, 0x00008009,
  0x0000008a, 0x00000088, 0x80008009, 0x8000000a, 0x8000808b, 0x0000008b, 0x00008089, 0x00008003,
  0x00008002, 0x00000080, 0x0000800a, 0x8000000a, 0x80008081, 0x00008080, 0x80000001, 0x80008008,
])

// ρ rotation amounts and the π lane permutation, generated by the canonical
// (x,y) walk so there is no hand-copied table to get wrong. PI is the target
// slot (×2, low word) each step writes to.
const PI: number[] = []
const ROTL: number[] = []
{
  let x = 1
  let y = 0
  for (let t = 0; t < 24; t++) {
    ;[x, y] = [y, (2 * x + 3 * y) % 5]
    PI.push(2 * (5 * y + x))
    ROTL.push((((t + 1) * (t + 2)) / 2) % 64)
  }
}

// 64-bit left-rotate of a (high, low) pair, split into the <32 and >32 cases.
const rotlH = (h: number, l: number, s: number): number =>
  s < 32 ? (h << s) | (l >>> (32 - s)) : (l << (s - 32)) | (h >>> (64 - s))
const rotlL = (h: number, l: number, s: number): number =>
  s < 32 ? (l << s) | (h >>> (32 - s)) : (h << (s - 32)) | (l >>> (64 - s))

const B = new Uint32Array(10) // scratch shared across permutations

/** Keccak-f[1600] on the split-word state, in place (24 rounds). */
function keccakF(s: Uint32Array): void {
  for (let round = 0; round < 24; round++) {
    // θ — column parities, then rotate-and-fold each column into its lanes.
    for (let xx = 0; xx < 10; xx++) B[xx] = s[xx] ^ s[xx + 10] ^ s[xx + 20] ^ s[xx + 30] ^ s[xx + 40]
    for (let xx = 0; xx < 10; xx += 2) {
      const i0 = (xx + 2) % 10
      const i1 = (xx + 8) % 10
      const th = rotlH(B[i0], B[i0 + 1], 1) ^ B[i1]
      const tl = rotlL(B[i0], B[i0 + 1], 1) ^ B[i1 + 1]
      for (let yy = 0; yy < 50; yy += 10) {
        s[xx + yy] ^= th
        s[xx + yy + 1] ^= tl
      }
    }
    // ρ (rotate) and π (permute), threaded through the 24-step cycle.
    let curH = s[2]
    let curL = s[3]
    for (let t = 0; t < 24; t++) {
      const shift = ROTL[t]
      const th = rotlH(curH, curL, shift)
      const tl = rotlL(curH, curL, shift)
      const p = PI[t]
      curH = s[p]
      curL = s[p + 1]
      s[p] = th
      s[p + 1] = tl
    }
    // χ — the only non-linear step, per 5-lane row.
    for (let yy = 0; yy < 50; yy += 10) {
      for (let xx = 0; xx < 10; xx++) B[xx] = s[yy + xx]
      for (let xx = 0; xx < 10; xx++) s[yy + xx] ^= ~B[(xx + 2) % 10] & B[(xx + 4) % 10]
    }
    // ι — break the round's symmetry.
    s[0] ^= RC_LO[round]
    s[1] ^= RC_HI[round]
  }
}

/**
 * An incremental Keccak sponge. It backs both the one-shot digests below and
 * the streaming uses ML-KEM's test harness needs: a SHAKE128 instance seeded
 * once and squeezed on demand (the deterministic RNG), and an accumulator you
 * absorb many byte strings into before squeezing a single tag.
 */
export class Keccak {
  private state = new Uint32Array(50) // 25 lanes, little-endian split words
  private pos = 0 // byte cursor: absorb offset, then squeeze offset
  private squeezing = false
  private readonly rate: number
  private readonly suffix: number
  constructor(rate: number, suffix: number) {
    this.rate = rate
    this.suffix = suffix
  }

  // XOR one byte into the state at little-endian byte offset `o`.
  private xorByte(o: number, b: number): void {
    const idx = (o >> 3) * 2 + (o & 4 ? 1 : 0)
    const shift = (o & 3) * 8
    this.state[idx] = (this.state[idx] ^ (b << shift)) >>> 0
  }

  // Read one byte from the state at little-endian byte offset `o`.
  private getByte(o: number): number {
    const idx = (o >> 3) * 2 + (o & 4 ? 1 : 0)
    const shift = (o & 3) * 8
    return (this.state[idx] >>> shift) & 0xff
  }

  absorb(data: Uint8Array): this {
    if (this.squeezing) throw new Error('cannot absorb after squeezing')
    for (let i = 0; i < data.length; i++) {
      this.xorByte(this.pos++, data[i])
      if (this.pos === this.rate) {
        keccakF(this.state)
        this.pos = 0
      }
    }
    return this
  }

  private finish(): void {
    this.xorByte(this.pos, this.suffix)
    this.xorByte(this.rate - 1, 0x80)
    keccakF(this.state)
    this.pos = 0
    this.squeezing = true
  }

  squeeze(len: number): Uint8Array {
    if (!this.squeezing) this.finish()
    const out = new Uint8Array(len)
    for (let o = 0; o < len; o++) {
      if (this.pos === this.rate) {
        keccakF(this.state)
        this.pos = 0
      }
      out[o] = this.getByte(this.pos++)
    }
    return out
  }
}

function digest(rate: number, suffix: number, msg: Uint8Array, outLen: number): Uint8Array {
  return new Keccak(rate, suffix).absorb(msg).squeeze(outLen)
}

// Rates in bytes: rate = (1600 − capacity)/8, capacity = 2·(security level).
export const sha3_256 = (m: Uint8Array): Uint8Array => digest(136, 0x06, m, 32)
export const sha3_512 = (m: Uint8Array): Uint8Array => digest(72, 0x06, m, 64)
export const shake128 = (m: Uint8Array, outLen: number): Uint8Array => digest(168, 0x1f, m, outLen)
export const shake256 = (m: Uint8Array, outLen: number): Uint8Array => digest(136, 0x1f, m, outLen)

/** A SHAKE128 extendable stream seeded once, squeezed lazily (the test RNG). */
export function shake128Stream(seed: Uint8Array): { read: (n: number) => Uint8Array } {
  const k = new Keccak(168, 0x1f).absorb(seed)
  return { read: (n: number) => k.squeeze(n) }
}
